BEGIN;

DO $$
BEGIN
    CREATE TYPE public.gudang_tipe_enum AS ENUM ('Versa', 'Heksa', 'MAXI 24', 'VERTA 56');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
    CREATE TYPE public.gudang_status_enum AS ENUM ('tersedia', 'sedang di-keep', 'tidak tersedia', 'digunakan');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END
$$;

DO $$
BEGIN
    CREATE TYPE public.temu_janji_status_enum AS ENUM ('pending', 'approved', 'rejected', 'completed', 'canceled');
EXCEPTION
    WHEN duplicate_object THEN NULL;
END
$$;

CREATE TABLE IF NOT EXISTS public."user" (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.gudang (
    id UUID PRIMARY KEY,
    unit_code VARCHAR(20) NOT NULL UNIQUE,
    blok VARCHAR(10),
    tipe_gudang public.gudang_tipe_enum NOT NULL,
    tinggi NUMERIC(10, 2),
    kavling_l NUMERIC(10, 2),
    kavling_p NUMERIC(10, 2),
    luas_kavling NUMERIC(10, 2),
    lt1_l NUMERIC(10, 2),
    lt1_p NUMERIC(10, 2),
    luas_lt1 NUMERIC(10, 2),
    lt2_l NUMERIC(10, 2),
    lt2_p NUMERIC(10, 2),
    extra_m2 NUMERIC(10, 2) NOT NULL DEFAULT 0,
    luas_lt2 NUMERIC(10, 2),
    pos_l NUMERIC(10, 2),
    pos_p NUMERIC(10, 2),
    luas_pos NUMERIC(10, 2),
    total_luas_bangunan NUMERIC(10, 2),
    grand_total NUMERIC(10, 2),
    foto JSONB,
    harga_sewa NUMERIC(14, 2) DEFAULT 0,
    status public.gudang_status_enum DEFAULT 'tersedia',
    fasilitas JSONB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.jadwal (
    id UUID PRIMARY KEY,
    jam_mulai TIME WITHOUT TIME ZONE NOT NULL,
    jam_selesai TIME WITHOUT TIME ZONE NOT NULL,
    kuota INTEGER NOT NULL DEFAULT 1 CHECK (kuota >= 1),
    status_aktif BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT jadwal_jam_berurutan CHECK (jam_selesai > jam_mulai),
    CONSTRAINT jadwal_jam_unique UNIQUE (jam_mulai, jam_selesai)
);

CREATE TABLE IF NOT EXISTS public.temu_janji (
    id UUID PRIMARY KEY,
    kode_booking VARCHAR(30) NOT NULL UNIQUE,
    gudang_id UUID NOT NULL REFERENCES public.gudang (id) ON DELETE RESTRICT,
    nama_perusahaan VARCHAR(150) NOT NULL,
    nama_pic VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL,
    no_telepon VARCHAR(30) NOT NULL,
    tanggal_kunjungan DATE NOT NULL,
    jam_mulai TIME WITHOUT TIME ZONE NOT NULL,
    jam_selesai TIME WITHOUT TIME ZONE NOT NULL,
    catatan TEXT,
    status public.temu_janji_status_enum NOT NULL DEFAULT 'pending',
    created_at TIMESTAMP WITH TIME ZONE,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT temu_janji_jam_berurutan CHECK (jam_selesai > jam_mulai)
);

CREATE INDEX IF NOT EXISTS temu_janji_kapasitas_idx
    ON public.temu_janji (tanggal_kunjungan, jam_mulai, jam_selesai, status);
CREATE INDEX IF NOT EXISTS temu_janji_gudang_status_idx
    ON public.temu_janji (gudang_id, status);

COMMIT;
